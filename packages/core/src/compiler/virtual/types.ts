/**
 * The per-realm `.d.ts` files of the virtual-module table. Nothing in them is typed by hand: each
 * declaration points TypeScript at the code that knows the module.
 *
 *   value    `ValueOf<typeof entry>['name']`: what the entry's `from` returns
 *   request  re-exported from the real module, so its own types are the types
 *   family   `ModuleOf<typeof entry>['name']`: the `contract/` interface the entry is typed with
 *
 * Each file declares its realm module (`ogygia:server`: every entry's names), and each entry's own
 * id (by the module's own names) for the code that imports a
 * module by id: a module that only runs, a lazy one. The files sit at `packages/core/virtual/`,
 * beside `dist/`, and point into the built package (the same place in the workspace and in the
 * published one). `scripts/virtual-types.ts` writes them; a test fails while they are stale.
 */
import { dedent } from '../dedent.ts';
import {
	OGYGIA_SCHEME,
	realm_exports,
	specifier,
	specifier_of,
	value_names,
	type Entry,
	type Leg,
	type ModuleEntry,
	type Realm,
	type ValueEntry,
	type ValueNames
} from './table.ts';

/**
 * Each value entry's export names, by specifier: the keys of its `from` run once against `probe` (a
 * session and leg that read nothing off disk). Sorted by specifier, so the generated file is stable.
 */
export function probe_value_names<A>(
	entries: readonly Entry<A>[],
	probe: A,
	leg: Leg
): Record<string, string[]> {
	const out: Record<string, string[]> = {};
	const values = entries.filter((e): e is ValueEntry<A, object> => e.kind === 'value');
	for (const e of values.sort((a, b) => (specifier_of(a) < specifier_of(b) ? -1 : 1)))
		out[specifier_of(e)] = Object.keys(e.from(probe, leg));
	return out;
}

/** The generated names module (./value-names.ts). */
export function value_names_source(names: Record<string, string[]>): string {
	const lines = Object.entries(names).map(
		([id, list]) => `\t${JSON.stringify(id)}: [${list.map((n) => JSON.stringify(n)).join(', ')}]`
	);
	return (
		dedent`
			// Each value entry's export names. GENERATED by \`node packages/core/scripts/virtual-types.ts\`
			// from a probe run of the entries' \`from\` (src/compiler/virtual/types.ts). Do not edit.
			import type { ValueNames } from './table.ts';

			export const CORE_VALUE_NAMES: ValueNames = {
		` +
		'\n' +
		lines.join(',\n') +
		'\n};\n'
	);
}

export const REALMS: readonly Realm[] = ['server', 'boot', 'region', 'dev'];

/** Where the generated files reach the built package from. */
const DIST = '../dist';
const TABLE = `import('${DIST}/compiler/virtual/table.js')`;
/** Core's entries, built (./core.ts). */
export const CORE_ENTRIES_PATH: string = `${DIST}/compiler/virtual/core.js`;

const request_from = (e: ModuleEntry<unknown> & { kind: 'request' }): string =>
	'core' in e.module ? `${DIST}/${e.module.core}.js` : e.module.package;

/** An entry's lines in its realm module: each name it gives the realm, typed off the entry. */
function realm_lines(e: ModuleEntry<unknown>, entry: string, value: ValueNames): string[] {
	const names = realm_exports(e, value);
	if (names.length === 0) return [];
	if (e.kind === 'request') {
		const list = names.map(([name, own]) => (own === name ? name : `${own} as ${name}`));
		return [`export { ${list.join(', ')} } from '${request_from(e)}';`];
	}
	const of = e.kind === 'value' ? 'ValueOf' : 'ModuleOf';
	return names.map(([name, own]) => `export const ${name}: ${TABLE}.${of}<${entry}>['${own}'];`);
}

/** An entry's own module, by its own names. */
function own_body(e: ModuleEntry<unknown>, entry: string, value: ValueNames): string {
	if (e.kind === 'value')
		return value_names(e, value)
			.map((n: string) => `export const ${n}: ${TABLE}.ValueOf<${entry}>['${n}'];`)
			.join('\n');
	if (e.kind === 'request')
		return `export { ${[...new Set(Object.values(e.exports))].join(', ')} } from '${request_from(e)}';`;
	return dedent`
		const module: ${TABLE}.ModuleOf<${entry}>;
		export = module;
	`;
}

const declare = (name: string, text: string): string =>
	dedent`
		declare module '${name}' {
		${text}
		}
	` + '\n';

/** The constants' globals (`declare const __OGYGIA_X__`), each typed `ConstOf<typeof entry>`. */
export function constant_types(entries: Record<string, unknown>, entries_path: string): string {
	const lines: string[] = [];
	for (const [name, value] of Object.entries(entries).sort(([a], [b]) => (a < b ? -1 : 1))) {
		const e = value as { kind?: string; id?: string };
		if (typeof e !== 'object' || e === null || e.kind !== 'constant') continue;
		lines.push(
			`declare const ${e.id}: ${TABLE}.ConstOf<typeof import('${entries_path}').${name}>;`
		);
	}
	return (
		dedent`
			// ogygia's switches, the \`define\`s its build inlines. GENERATED from the virtual-module
			// table's constants (packages/core/src/compiler/virtual/core.ts) by
			// \`node packages/core/scripts/virtual-types.ts\`. Do not edit.
		` +
		'\n\n' +
		lines.join('\n') +
		'\n'
	);
}

/**
 * The `.d.ts` text of each realm. `entries` is the module that exports the table's entries, by
 * export name (`entries_path`: its built path, relative to the generated files). A prefix family
 * declares nothing: its members are generated per file.
 */
export function virtual_types<A>(
	entries: Record<string, unknown>,
	entries_path: string,
	names: ValueNames
): Record<Realm, string> {
	const out = {} as Record<Realm, string>;
	// (by export name: a module namespace's key order depends on the loader)
	const sorted = Object.entries(entries).sort(([a], [b]) => (a < b ? -1 : 1));
	for (const realm of REALMS) {
		const realm_module: string[] = [];
		let own = '';
		for (const [name, value] of sorted) {
			const e = value as Entry<A>;
			if (typeof e !== 'object' || e === null || !('kind' in e) || e.kind === 'constant') continue;
			if (e.realm !== realm || (e.kind === 'family' && (e.parse || !e.load))) continue;
			const entry = `typeof import('${entries_path}').${name}`;
			const m = e as ModuleEntry<unknown>;
			realm_module.push(...realm_lines(m, entry, names));
			own += declare(specifier(realm, m.id), own_body(m, entry, names));
		}
		out[realm] =
			dedent`
				// The \`ogygia:${realm}\` module and its entries' own ids. GENERATED from the virtual-module
				// table (packages/core/src/compiler/virtual/core.ts) by
				// \`node packages/core/scripts/virtual-types.ts\`; every type is read off the code (see
				// src/compiler/virtual/types.ts). Do not edit.
			` +
			'\n\n' +
			declare(OGYGIA_SCHEME + realm, realm_module.join('\n')) +
			own;
	}
	return out;
}
